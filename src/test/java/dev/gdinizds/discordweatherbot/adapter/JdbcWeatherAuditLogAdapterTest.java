package dev.gdinizds.discordweatherbot.adapter;

import dev.gdinizds.discordweatherbot.adapter.out.persistence.JdbcWeatherAuditLogAdapter;
import dev.gdinizds.discordweatherbot.config.Resilience;
import dev.gdinizds.discordweatherbot.domain.model.WeatherAuditLog;
import io.github.resilience4j.bulkhead.BulkheadRegistry;
import io.github.resilience4j.circuitbreaker.CircuitBreakerRegistry;
import io.github.resilience4j.retry.RetryRegistry;
import io.github.resilience4j.timelimiter.TimeLimiterRegistry;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.util.concurrent.Executors;

import static org.assertj.core.api.Assertions.assertThat;

class JdbcWeatherAuditLogAdapterTest {

    private JdbcTemplate jdbcTemplate;
    private JdbcWeatherAuditLogAdapter adapter;

    @BeforeEach
    void setUp() {
        var ds = new DriverManagerDataSource();
        ds.setDriverClassName("org.h2.Driver");
        ds.setUrl("jdbc:h2:mem:weather_test_audit;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DEFAULT_NULL_ORDERING=HIGH;DB_CLOSE_DELAY=-1");
        ds.setUsername("sa");
        ds.setPassword("");

        jdbcTemplate = new JdbcTemplate(ds);

        jdbcTemplate.execute("CREATE SCHEMA IF NOT EXISTS weather_bot");
        jdbcTemplate.execute("""
                CREATE TABLE IF NOT EXISTS weather_bot.weather_audit_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    correlation_id VARCHAR(64) NOT NULL,
                    guild_id VARCHAR(32),
                    channel_id VARCHAR(32),
                    user_id VARCHAR(32) NOT NULL,
                    command_name VARCHAR(32) NOT NULL,
                    trigger_type VARCHAR(16) NOT NULL,
                    query_location VARCHAR(256),
                    resolved_location VARCHAR(256),
                    status VARCHAR(32) NOT NULL,
                    raw_request TEXT,
                    raw_response TEXT,
                    execution_time_ms BIGINT NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL
                )
                """);

        var resilience = new Resilience(
                CircuitBreakerRegistry.ofDefaults(),
                RetryRegistry.ofDefaults(),
                TimeLimiterRegistry.ofDefaults(),
                BulkheadRegistry.ofDefaults(),
                Executors.newVirtualThreadPerTaskExecutor()
        );

        adapter = new JdbcWeatherAuditLogAdapter(jdbcTemplate, resilience);
    }

    @Test
    void shouldSaveAuditLogEntry() {
        WeatherAuditLog log = WeatherAuditLog.create(
                "corr-1", "g1", "ch1", "u1", "clima", "SLASH",
                "São Paulo", "São Paulo, SP - Brasil", "SUCCESS",
                "{}", "sessionId=s1", 125L
        );

        adapter.save(log);

        Integer count = jdbcTemplate.queryForObject(
                "SELECT count(*) FROM weather_bot.weather_audit_log WHERE correlation_id = 'corr-1'",
                Integer.class
        );
        assertThat(count).isEqualTo(1);
    }
}
